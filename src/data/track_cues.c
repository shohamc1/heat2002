/* One HUD cue: UpdateTrackCues (src/hud/track_cues.c) shows the icon once
   the car's lap progress reaches progress, and hides it at end. */
struct TrackCue {
    u16 progress;
    /* bits 0-2 pick the gTrackCueIconGfxList sprite; bit 3 flips it
       horizontally, bit 4 vertically */
    u8 icon;
    /* DrawTrackCueIcon's angle: 0, or 0x40 and 0xC0 for a rotated icon */
    u16 angle;
    /* 0 keeps the icon up until the next cue */
    u16 end;
};

